"""종류 수와 선택 가능 수의 작은 값.

복잡도: O(n) time, O(n) space
이 저장소를 위해 효율성과 제한 조건을 기준으로 독립 작성한 권장 풀이입니다.
"""

def solution(nums):
    # 이 구현의 선택: 종류 수와 선택 가능 수의 작은 값
    # 상태 정의: 서로 다른 종류 수와 뽑을 수 있는 총 마릿수만 남긴다.
    # 핵심 불변식: 한 종류에서 두 마리 이상 고르는 선택은 종류 수를 늘리지 않는다.
    # 서로 다른 종류를 한 마리씩 먼저 고를 수 있지만 총 선택 수 N/2를 넘을 수 없다.
    return min(len(set(nums)), len(nums) // 2)
