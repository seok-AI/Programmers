def audited_constraint_errors(lesson_id: int, args: list[object]) -> list[str]:
    """호환 이름을 유지하면서 57문제 전체 제한 검증기로 위임한다."""
    return constraint_errors(lesson_id, args)


def main() -> int:
    directories = {
        problem_id(path.parent): path.parent
        for path in ROOT.glob("[0-9][0-9]_*/**/tests.json")
    }
    missing = sorted(set(directories) - set(EDGE_CASES))
    extra = sorted(set(EDGE_CASES) - set(directories))
    if missing or extra:
        raise ValueError(f"경계 테스트 ID 불일치: missing={missing}, extra={extra}")

    total = 0
    for lesson_id, directory in directories.items():
        tests = EDGE_CASES[lesson_id]
        for index, test in enumerate(tests, start=1):
            violations = audited_constraint_errors(lesson_id, test["args"])
            if violations:
                details = "; ".join(violations)
                raise ValueError(f"{lesson_id} 경계 테스트 {index} 명세 위반: {details}")
        (directory / "edge_tests.json").write_text(
            json.dumps(tests, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8",
        )
        total += len(tests)
    print(f"경계 테스트 생성 완료: {len(directories)}문제, {total}개")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
